-- 1. Extend office_settings with Jarvis Autonomy Policy controls
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' 
      AND table_name = 'office_settings' 
      AND column_name = 'jarvis_autonomy_mode'
  ) THEN
    ALTER TABLE public.office_settings 
    ADD COLUMN jarvis_autonomy_mode text NOT NULL DEFAULT 'STANDING_POLICY' 
    CHECK (jarvis_autonomy_mode IN ('ASK_FOR_ALL', 'STANDING_POLICY', 'OFF'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' 
      AND table_name = 'office_settings' 
      AND column_name = 'department_break_cap_pct'
  ) THEN
    ALTER TABLE public.office_settings 
    ADD COLUMN department_break_cap_pct integer NOT NULL DEFAULT 30;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' 
      AND table_name = 'office_settings' 
      AND column_name = 'max_personal_break_minutes'
  ) THEN
    ALTER TABLE public.office_settings 
    ADD COLUMN max_personal_break_minutes integer NOT NULL DEFAULT 10;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' 
      AND table_name = 'office_settings' 
      AND column_name = 'quiet_hours_enabled'
  ) THEN
    ALTER TABLE public.office_settings 
    ADD COLUMN quiet_hours_enabled boolean NOT NULL DEFAULT false;
  END IF;
END $$;

-- 2. Extend office_agent_needs with Pin Status (Never rest vs Must rest)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_schema = 'public' 
      AND table_name = 'office_agent_needs' 
      AND column_name = 'pin_status'
  ) THEN
    ALTER TABLE public.office_agent_needs 
    ADD COLUMN pin_status text NOT NULL DEFAULT 'NORMAL' 
    CHECK (pin_status IN ('NORMAL', 'NEVER_REST', 'MUST_REST'));
  END IF;
END $$;

-- 3. Remembered Preferences for Jarvis (Learned operator governance decisions)
CREATE TABLE IF NOT EXISTS public.office_wellness_preferences (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  operator_action text NOT NULL CHECK (operator_action IN ('approve', 'reject', 'hold', 'send_back', 'instruct')),
  category text NOT NULL,
  agent_id text REFERENCES public.office_agents(id) ON DELETE SET NULL,
  department text,
  reason text NOT NULL,
  instruction text,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- 4. Daily Morning Schedule Plans generated by Jarvis
CREATE TABLE IF NOT EXISTS public.office_daily_schedules (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  date date NOT NULL,
  schedule jsonb NOT NULL,
  approval_id uuid,
  status text NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'approved', 'rejected', 'in_progress', 'completed')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_office_daily_schedules_date UNIQUE (date)
);

-- 5. Enable RLS and Idempotent Policies
ALTER TABLE public.office_wellness_preferences ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.office_daily_schedules ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'office_wellness_preferences' 
      AND policyname = 'Allow read office_wellness_preferences'
  ) THEN
    CREATE POLICY "Allow read office_wellness_preferences" 
    ON public.office_wellness_preferences FOR SELECT USING (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'office_wellness_preferences' 
      AND policyname = 'Allow insert office_wellness_preferences'
  ) THEN
    CREATE POLICY "Allow insert office_wellness_preferences" 
    ON public.office_wellness_preferences FOR INSERT WITH CHECK (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies 
    WHERE tablename = 'office_daily_schedules' 
      AND policyname = 'Allow read office_daily_schedules'
  ) THEN
    CREATE POLICY "Allow read office_daily_schedules" 
    ON public.office_daily_schedules FOR SELECT USING (true);
